// ---------- Persist --------------------------------------------------------

func (g *Generator) persist(r *Report) {
	dir := filepath.Join(g.workDir, "data", "reports")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return
	}
	path := filepath.Join(dir, r.Date+".json")
	f, err := os.Create(path)
	if err != nil {
		return
	}
	defer func() {
		if err := f.Close(); err != nil {
			log.Printf("[DailyReport] close persist file: %v", err)
		}
	}()
	if err := json.NewEncoder(f).Encode(r); err != nil {
		log.Printf("[DailyReport] encode persist: %v", err)
	}
}

// Latest returns the most recent report.
func (g *Generator) Latest() *Report {
	g.mu.RLock()
	defer g.mu.RUnlock()
	return g.latest
}

// GetByDate returns a specific date's report.
func (g *Generator) GetByDate(date string) *Report {
	g.mu.RLock()
	defer g.mu.RUnlock()
	return g.archive[date]
}

// Revise applies a human revision to the report for date, persists the
// corrected version (revision history stays inside the report file) and
// returns the updated report. The corrected report becomes the downstream
// version — it replaces the in-memory archive entry and the on-disk file.
func (g *Generator) Revise(date string, req ReviseRequest) (*Report, error) {
	g.mu.Lock()
	r := g.archive[date]
	if r == nil {
		g.mu.Unlock()
		return nil, fmt.Errorf("%w: %s", errReportNotFound, date)
	}
	if err := r.ApplyRevision(req); err != nil {
		g.mu.Unlock()
		return nil, err
	}
	g.mu.Unlock()

	g.persist(r)
	return r, nil
}

// Approve marks the report for date as approved without revision.
func (g *Generator) Approve(date string) (*Report, error) {
	g.mu.Lock()
	r := g.archive[date]
	if r == nil {
		g.mu.Unlock()
		return nil, fmt.Errorf("%w: %s", errReportNotFound, date)
	}
	if err := r.Approve(); err != nil {
		g.mu.Unlock()
		return nil, err
	}
	g.mu.Unlock()

	g.persist(r)
	return r, nil
}

// ---------- HTTP Handlers -------------------------------------------------

type Handler struct {
	gen     *Generator
	tracker *Tracker
}

func NewHandler(gen *Generator, tracker *Tracker) *Handler {
	return &Handler{gen: gen, tracker: tracker}
}

func (h *Handler) HandleLatest(w http.ResponseWriter, r *http.Request) {
	rep := h.gen.Latest()
	if rep == nil {
		rep = h.gen.Generate()
	}
	format := r.URL.Query().Get("format")
	w.Header().Set("Content-Type", "application/json")
	if format == "markdown" {
		w.Header().Set("Content-Type", "text/markdown; charset=utf-8")
		_, _ = w.Write([]byte(rep.Markdown()))
		return
	}
	if err := json.NewEncoder(w).Encode(rep); err != nil {
		log.Printf("[DailyReport] encode latest: %v", err)
	}
}

func (h *Handler) HandleArchive(w http.ResponseWriter, r *http.Request) {
	date := r.URL.Query().Get("date")
	if date == "" {
		http.Error(w, "?date=YYYY-MM-DD required", http.StatusBadRequest)
		return
	}
	rep := h.gen.GetByDate(date)
	if rep == nil {
		http.Error(w, "not found", http.StatusNotFound)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	if err := json.NewEncoder(w).Encode(rep); err != nil {
		log.Printf("[DailyReport] encode archive: %v", err)
	}
}

func (h *Handler) HandleSubscribe(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, "POST required", http.StatusMethodNotAllowed)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	if err := json.NewEncoder(w).Encode(map[string]string{"status": "subscribed"}); err != nil {
		log.Printf("[DailyReport] encode subscribe: %v", err)
	}
}

// RegisterRoutes installs the /api/reports/* endpoints. tracker may be nil
// (claims endpoints then return 503); the revise/approve endpoints are
// admin-auth guarded (same ATLAS_API_KEY policy as cmd/atlas wrapAdminAuth).
func RegisterRoutes(mux *http.ServeMux, gen *Generator, tracker *Tracker) {
	h := NewHandler(gen, tracker)
	mux.HandleFunc("GET /api/reports/latest", h.HandleLatest)
	// Deprecated: not yet implemented; reserved for v0.0.0.32. See docs/operations/tier-boundary.md.
	mux.HandleFunc("GET /api/reports/archive", h.HandleArchive)
	// Deprecated: not yet implemented; reserved for v0.0.0.32. See docs/operations/tier-boundary.md.
	mux.HandleFunc("POST /api/reports/subscribe", h.HandleSubscribe)

	// Stateful workflow: human-in-the-loop correction (2026-08-23).
	mux.HandleFunc("POST /api/reports/{date}/revise", wrapAdminAuth(h.HandleRevise))
	mux.HandleFunc("POST /api/reports/{date}/approve", wrapAdminAuth(h.HandleApprove))
	// Cross-day claim tracking query.
	mux.HandleFunc("GET /api/reports/tracked-claims", h.HandleTrackedClaims)
}
