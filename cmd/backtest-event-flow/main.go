// File: cmd/backtest-event-flow/main.go
// Package: main
//
// Stage 4 PR#3 — prediction backtest engine.
//
// Reads the 4 staging JSONL files produced by cmd/atlas-stage4-backfill
// (PR#1), reconstructs what the event-driven capital flow predictor
// WOULD have output on each historical trading day, and writes the
// (predicted, actual) pair to SQLite prediction_backtest so that
// PR#4 (template hit_rate recalculation) has statistically meaningful
// sample sizes.
//
// Design notes:
//   - The predictor wiring (calendar / capitalFlow / narrativeModels) is
//     replicated in-process for each historical date. refreshEvents +
//     annual rules give us the deterministic inputs the predictor would
//     have seen at runtime.
//   - The "actual" outcome for each date is taken from
//     prediction_actual_90d.jsonl (PR#1's aggregated realized market
//     returns). Where that file lacks a row (e.g. outage days) we fall
//     back to regime label as a coarse proxy and skip hit/miss scoring.
//   - All rows are stamped is_synthetic=1 because they were generated by
//     re-running a model after-the-fact. No live data is overwritten.
//
// CLI:
//
//	-db       string   SQLite path (default ./data/state/atlas.db)
//	-staging  string   staging JSONL dir (default ./data/staging)
//	-since    string   inclusive start date YYYY-MM-DD
//	-until    string   inclusive end date YYYY-MM-DD
//	-model    string   model_version tag (default "stage4-v1")
//	-dry-run  bool     parse and run predictor but skip SQLite writes
//	-init-schema bool   run ledger.InitSchema before ingesting
package main

