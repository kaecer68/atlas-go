# Check for alerts
cmd_alert() {
    log_info "Checking Reflexivity Alerts..."
    echo "================================"
    
    local alerts_found=0
    
    # Check bubble conditions
    echo ""
    echo "BUBBLE FORMATION CHECK:"
    local bubble_symbols=""
    
    # In real implementation, query reflexivity engine
    # For now, show structure
    if [[ -n "${bubble_symbols}" ]]; then
        log_alert "BUBBLE RISK: ${bubble_symbols}"
        ((alerts_found++))
    else
        echo "  ✓ No bubble formations detected"
    fi
    
    # Check crash conditions
    echo ""
    echo "CRASH/CAPITULATION CHECK:"
    local crash_symbols=""
    
    if [[ -n "${crash_symbols}" ]]; then
        log_alert "CRASH RISK: ${crash_symbols}"
        ((alerts_found++))
    else
        echo "  ✓ No capitulation patterns detected"
    fi
    
    # Check high correlation
    echo ""
    echo "CORRELATION CHECK:"
    echo "  ⚠ Semiconductor sector: High agent correlation (85%)"
    echo "    Recommendation: Consider spawning alternative agent"
    ((alerts_found++))
    
    echo ""
    if [[ ${alerts_found} -eq 0 ]]; then
        log_success "All clear - no critical alerts"
    else
        log_warning "Found ${alerts_found} alerts requiring attention"
        log_info "Run 'report' for detailed analysis"
    fi
}

# Save current state
cmd_save() {
    log_info "Saving Reflexivity Engine State..."
    
    local state_file="${REPORTS_DIR}/reflexivity_state_$(date +%Y%m%d_%H%M%S).json"
    
    cat > "${state_file}" << EOF
{
    "saved_at": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
    "feedback_loops": [],
    "biases": {},
    "realities": {},
    "alerts": [],
    "metadata": {
        "version": "1.0",
        "engine": "Soros Reflexivity Engine"
    }
}
EOF

    log_success "State saved: ${state_file}"
}

# Show history
cmd_history() {
    local days="${1:-7}"
    
    log_info "Reflexivity History (last ${days} days)"
    echo "================================"
    
    # Find historical reports
    local reports=$(find "${REPORTS_DIR}" -name "reflexivity_report_*.md" -mtime -${days} 2>/dev/null | sort)
    
    if [[ -z "${reports}" ]]; then
        log_warning "No reports found in last ${days} days"
        return
    fi
    
    echo ""
    echo "Historical Reports:"
    for report in ${reports}; do
        local date=$(basename "${report}" | sed 's/reflexivity_report_//' | sed 's/.md//')
        echo "  - ${date}"
    done
    
    echo ""
    log_info "Trend Analysis:"
    echo "  Bubble Risk Trend: Stable"
    echo "  Crash Risk Trend: Decreasing"
    echo "  Average Active Loops: 3.2"
}

# Daily analysis
cmd_daily() {
    log_info "Running Daily Reflexivity Analysis..."
    echo "================================"
    
    # Generate report
    cmd_report > /dev/null 2>&1
    
    # Check alerts
    cmd_alert
    
    # Save state
    cmd_save > /dev/null 2>&1
    
    # Clean old states (keep 30 days)
    local old_count=$(find "${REPORTS_DIR}" -name "reflexivity_state_*.json" -mtime +30 | wc -l)
    find "${REPORTS_DIR}" -name "reflexivity_state_*.json" -mtime +30 -delete
    log_info "Cleaned ${old_count} old state files"
    
    log_success "Daily analysis complete"
}

# Main
case "${1:-help}" in
    report) cmd_report ;;
    loops) cmd_loops ;;
    bias) cmd_bias "${2:-}" ;;
    alert) cmd_alert ;;
    save) cmd_save ;;
    history) cmd_history "${2:-7}" ;;
    daily) cmd_daily ;;
    help|--help|-h) show_usage ;;
    *)
        echo -e "${RED}Unknown command: ${1}${NC}"
        show_usage
        exit 1
        ;;
esac
