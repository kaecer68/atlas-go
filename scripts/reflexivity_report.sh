    # Show summary
    echo ""
    echo "=========================================="
    echo "  REFLEXIVITY ANALYSIS SUMMARY"
    echo "=========================================="
    echo "  Bubble Risk:     ${bubble_risk}/10"
    echo "  Crash Risk:      ${crash_risk}/10"
    echo "  Active Loops:    Detected"
    echo "  Last Updated:    ${timestamp}"
    echo "=========================================="
    echo ""
    
    cat "${report_file}"
}

