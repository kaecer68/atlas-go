#!/bin/bash
#
# Soros Reflexivity Engine Report Script
# Generates feedback loop analysis and market bias reports
#

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
REPORTS_DIR="${PROJECT_ROOT}/reports"
LOG_DIR="${PROJECT_ROOT}/logs"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m'

log_info() { echo -e "${BLUE}[Reflexivity]${NC} $1"; }
log_success() { echo -e "${GREEN}[Reflexivity]${NC} $1"; }
log_warning() { echo -e "${YELLOW}[Reflexivity]${NC} $1"; }
log_alert() { echo -e "${RED}[ALERT]${NC} $1"; }

mkdir -p "${REPORTS_DIR}" "${LOG_DIR}"

show_usage() {
    cat << EOF
Soros Reflexivity Engine Report Script

Usage: $0 [command] [options]

Commands:
    report              Generate comprehensive reflexivity report
    loops               Show active feedback loops
    bias [symbol]       Show bias analysis for specific symbol
    alert               Check for bubble/crash alerts
    save                Save current reflexivity state
    history [days]      Show historical analysis (default: 7 days)
    daily               Run daily reflexivity analysis
    help                Show this help message

Examples:
    $0 report
    $0 bias 2330.TW
    $0 alert
    $0 daily

EOF
}

