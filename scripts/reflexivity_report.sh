### Negative Feedback (Self-Correcting)

| Symbol | Bias Type | Strength | Prediction | Confidence |
|--------|-----------|----------|------------|------------|
EOF

    cat >> "${report_file}" << EOF
| 2881.TW | Contrarian | 0.45 | Mean reversion likely | 72% |

## Market Bias Distribution

### By Type

- Trend Following: Moderate
- Herding: Elevated in semiconductors
- Fear/Greed: Neutral
- Overconfidence: Low

