    fi

    if [[ ${crash_risk} -gt 7 ]]; then
        cat >> "${report_file}" << EOF
### 🔴 HIGH: Capitulation Risk

Strong negative bias momentum. Recommend:
- Prepare dry powder
- Watch for reversal signals
- Defensive positioning

EOF
    fi

    cat >> "${report_file}" << EOF
